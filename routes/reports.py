"""Report generation routes — PDF and Word"""
import os
import uuid
from datetime import datetime

from flask import Blueprint, request, jsonify, send_file, g, current_app

from database import SessionLocal
from models import Farm, Season
from routes.auth import login_required

reports_bp = Blueprint("reports", __name__)

REPORTS_DIR = os.getenv("REPORT_STORAGE_PATH", "./reports")


def _db():
    return SessionLocal()


def _report_path(report_id: str, ext: str) -> str:
    os.makedirs(REPORTS_DIR, exist_ok=True)
    return os.path.join(REPORTS_DIR, f"{report_id}{ext}")


# ─── PDF generator ────────────────────────────────────────────────────────────
def _gen_pdf(farm, season, dest_path: str) -> bool:
    try:
        from reportlab.lib import colors
        from reportlab.lib.enums import TA_CENTER
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import inch
        from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle, Image as RLImage

        doc = SimpleDocTemplate(dest_path, pagesize=A4)
        styles = getSampleStyleSheet()
        elems = []

        # ── Logo ──────────────────────────────────────────────────────────────
        logo_path = os.path.join(os.path.dirname(__file__), '..', 'static', 'img', 'sawie-logo.png')
        if os.path.exists(logo_path):
            logo = RLImage(logo_path, width=0.96*inch, height=1.1*inch)
            logo.hAlign = 'CENTER'
            elems.append(logo)
            elems.append(Spacer(1, 0.1*inch))

        title_style = ParagraphStyle(
            "CL_Title", parent=styles["Heading1"],
            fontSize=24, textColor=colors.HexColor("#0a7a34"),
            spaceAfter=30, alignment=TA_CENTER,
        )
        elems.append(Paragraph("CarbonLens Carbon Footprint Report", title_style))
        elems.append(Spacer(1, 0.3 * inch))

        farm_rows = [
            ["Farm Information", ""],
            ["Farm ID:", farm.farm_id],
            ["Farmer Name:", farm.farmer_name],
            ["Province:", farm.province],
            ["District:", farm.district],
            ["Area (acres):", str(farm.area)],
            ["Season:", season.season],
            ["Crop:", season.crop],
        ]
        ft = Table(farm_rows, colWidths=[2.5 * inch, 3.5 * inch])
        ft.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (1, 0), colors.HexColor("#0a7a34")),
            ("TEXTCOLOR", (0, 0), (1, 0), colors.whitesmoke),
            ("FONTNAME", (0, 0), (1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (1, 0), 14),
            ("BOTTOMPADDING", (0, 0), (1, 0), 12),
            ("GRID", (0, 0), (-1, -1), 1, colors.grey),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f2f9f2")]),
        ]))
        elems.append(ft)
        elems.append(Spacer(1, 0.5 * inch))

        if season.total_co2_equiv is not None:
            res_rows = [
                ["Carbon Footprint Results", ""],
                ["Total CO₂ Equivalent:", f"{season.total_co2_equiv:.2f} kg CO₂e"],
                ["Intensity:", f"{season.intensity_per_kg:.4f} kg CO₂e / kg seed cotton"],
                ["Calculation Date:", datetime.utcnow().strftime("%Y-%m-%d")],
            ]
            rt = Table(res_rows, colWidths=[2.5 * inch, 3.5 * inch])
            rt.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (1, 0), colors.HexColor("#159d45")),
                ("TEXTCOLOR", (0, 0), (1, 0), colors.whitesmoke),
                ("FONTNAME", (0, 0), (1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (1, 0), 14),
                ("BOTTOMPADDING", (0, 0), (1, 0), 12),
                ("GRID", (0, 0), (-1, -1), 1, colors.grey),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f2f9f2")]),
            ]))
            elems.append(rt)
            elems.append(Spacer(1, 0.5 * inch))

        elems.append(Paragraph(
            "<b>Disclaimer:</b> This report has been generated by the CarbonLens platform, developed by SAWiE "
            "(Sustainable Agriculture Water and Intelligent Ecosystems). The carbon footprint estimates are based solely "
            "on the data provided by the farmer and on IPCC Tier 1 &amp; Tier 2 emission factors applicable "
            "to Pakistan's agricultural context. SAWiE makes no warranty, express or implied, regarding the "
            "accuracy, completeness or fitness for any particular purpose of the results presented herein. "
            "SAWiE is not responsible for the accuracy or completeness of the farmer-provided data and shall not "
            "be liable for any loss, damage, claim or expense — direct or indirect — arising from reliance on this "
            "report or from any inaccuracy in the data entered. Users are advised to "
            "seek independent technical and agronomic advice before making decisions based on these estimates. "
            "© 2026 SAWiE Ecosystems (Private) Limited. All rights reserved.",
            styles["Normal"],
        ))
        doc.build(elems)
        return True
    except ImportError as e:
        print(f"[PDF] reportlab missing: {e}")
        return False


# ─── Word generator ───────────────────────────────────────────────────────────
def _gen_word(farm, season, dest_path: str) -> bool:
    try:
        from docx import Document
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.shared import Inches

        doc = Document()

        # ── Logo ──────────────────────────────────────────────────────────────
        logo_path = os.path.join(os.path.dirname(__file__), '..', 'static', 'img', 'sawie-logo.png')
        if os.path.exists(logo_path):
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run()
            run.add_picture(logo_path, width=Inches(1.2))
        t = doc.add_heading("CarbonLens Carbon Footprint Report", 0)
        t.alignment = WD_ALIGN_PARAGRAPH.CENTER

        doc.add_heading("Farm Information", level=1)
        tbl = doc.add_table(rows=8, cols=2)
        tbl.style = "Light Grid Accent 1"
        for i, (k, v) in enumerate([
            ("Farm ID", farm.farm_id),
            ("Farmer Name", farm.farmer_name),
            ("Province", farm.province),
            ("District", farm.district),
            ("Area (acres)", str(farm.area)),
            ("Season", season.season),
            ("Crop", season.crop),
            ("Yield (kg/acre)", str(season.seed_cotton_yield)),
        ]):
            tbl.rows[i].cells[0].text = k
            tbl.rows[i].cells[1].text = v

        if season.total_co2_equiv is not None:
            doc.add_heading("Carbon Footprint Results", level=1)
            doc.add_paragraph(f"Total CO₂ Equivalent: {season.total_co2_equiv:.2f} kg CO₂e")
            doc.add_paragraph(f"Intensity: {season.intensity_per_kg:.4f} kg CO₂e / kg seed cotton")

        doc.add_heading("Disclaimer", level=1)
        doc.add_paragraph(
            "This report has been generated by the CarbonLens platform, developed by SAWiE "
            "(Sustainable Agriculture Water and Intelligent Ecosystems). The carbon footprint estimates are based solely "
            "on the data provided by the farmer and on IPCC Tier 1 & Tier 2 emission factors applicable "
            "to Pakistan's agricultural context. SAWiE makes no warranty, express or implied, regarding the "
            "accuracy, completeness or fitness for any particular purpose of the results presented herein. "
            "SAWiE is not responsible for the accuracy or completeness of the farmer-provided data and shall not "
            "be liable for any loss, damage, claim or expense — direct or indirect — arising from reliance on this "
            "report or from any inaccuracy in the data entered. Users are advised to "
            "seek independent technical and agronomic advice before making decisions based on these estimates. "
            "\u00a9 2026 SAWiE Ecosystems (Private) Limited. All rights reserved."
        )
        doc.save(dest_path)
        return True
    except ImportError as e:
        print(f"[Word] python-docx missing: {e}")
        return False


# ─── Routes ───────────────────────────────────────────────────────────────────

@reports_bp.post("/")
@login_required
def create_report():
    data = request.get_json() or {}
    farm_id = data.get("farm_id")
    season_id = data.get("season_id")
    fmt = data.get("format", "pdf").lower()

    db = _db()
    try:
        farm = db.query(Farm).filter(
            Farm.id == farm_id, Farm.owner_id == g.current_user.id
        ).first()
        if not farm:
            return jsonify({"detail": "Farm not found"}), 404

        season = db.query(Season).filter(
            Season.id == season_id, Season.farm_id == farm_id
        ).first()
        if not season:
            return jsonify({"detail": "Season not found"}), 404

        report_id = str(uuid.uuid4())
        ext = ".pdf" if fmt == "pdf" else ".docx"
        path = _report_path(report_id, ext)

        ok = _gen_pdf(farm, season, path) if fmt == "pdf" else _gen_word(farm, season, path)
        if not ok:
            return jsonify({"detail": f"Failed to generate {fmt} report — library missing"}), 500

        return jsonify({
            "report_id": report_id,
            "farm_id": farm_id,
            "season_id": season_id,
            "created_at": str(datetime.utcnow()),
            "download_url": f"/api/reports/{report_id}/download?format={fmt}",
        })
    finally:
        db.close()


@reports_bp.get("/<report_id>/download")
@login_required
def download_report(report_id):
    fmt = request.args.get("format", "pdf").lower()
    ext = ".pdf" if fmt == "pdf" else ".docx"
    path = _report_path(report_id, ext)
    if not os.path.exists(path):
        return jsonify({"detail": "Report not found"}), 404
    mime = "application/pdf" if fmt == "pdf" else "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
    return send_file(path, mimetype=mime, as_attachment=True, download_name=f"CarbonLens_Report{ext}")
